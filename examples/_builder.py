"""Shared helpers for authoring the example schematics.

Why this exists rather than hand-written JSON: the first version of
`build_buck_converter.py` computed every terminal coordinate by hand from the
renderer's geometry, and the result was a document that drifted out of step
with the engine without anything noticing -- it used a block type
(`passive.switch.voltage`) the engine had stopped declaring, and two more
spellings the netlist emitter rejects.

So these helpers ask the engine for everything it can answer:

* `defaults_for` reads the required parameters and their defaults out of
  `gsim_py.catalog()`, so an example states only the values that make it the
  circuit it is -- 48 V in, 100 uH -- and inherits the rest. A parameter added
  to a component upstream therefore does not break every example.
* `add` fills those defaults in and passes the paradigm and domain the engine
  declares, instead of each script repeating them.
* placement and routing come from `Schematic.auto_arrange`.

Canonical names only. An alias such as `physical-electrical.source.voltage_dc`
resolves in the catalogue and in the symbol registry, and is then **rejected by
the netlist emitter** -- which is how an example could look correct in the
palette and fail to compile.
"""

from __future__ import annotations

import functools
import json
import pathlib
import re
from typing import Any

import gsim_py

#: Paradigm and domain per component, as the engine declares them. Passed on
#: every `add` because `Schematic.add` has no default for most types and raises
#: rather than guessing -- which is the right behaviour, just verbose.
_PLACEMENT_KEYS = ("paradigm", "domain")

#: The document schema, which is the contract a `.gsim_sch` file has to satisfy.
#: Reached by path because it is a sibling package's data file rather than
#: something importable.
_SCHEMA_PATH = (
    pathlib.Path(__file__).resolve().parent.parent
    / "packages"
    / "schemas"
    / "definitions"
    / "model"
    / "gsim_sch.schema.json"
)


@functools.lru_cache(maxsize=1)
def _schema_paradigm_rules() -> tuple[tuple[re.Pattern[str], str], ...]:
    r"""`(type pattern, required paradigm)` for each rule the schema states.

    Read out of the schema rather than restated here. The schema encodes this as a
    list of `if/then` pairs on `Block` -- `^routing\.` implies `paradigm: "routing"`,
    `^converter\.` implies `"converter"`, and so on -- and a hand-kept copy of that
    mapping is one more thing to drift. Every example is generated by this module,
    so a drift would silently make all five unopenable, which is exactly what
    happened the other way round (#146).
    """
    schema = json.loads(_SCHEMA_PATH.read_text())
    defs = schema.get("$defs") or schema.get("definitions") or {}
    rules: list[tuple[re.Pattern[str], str]] = []
    for clause in defs.get("Block", {}).get("allOf", []):
        pattern = clause.get("if", {}).get("properties", {}).get("type", {}).get("pattern")
        paradigm = clause.get("then", {}).get("properties", {}).get("paradigm", {}).get("const")
        if pattern and paradigm:
            rules.append((re.compile(pattern), paradigm))
    if not rules:
        raise RuntimeError(
            f"no type->paradigm rules found in {_SCHEMA_PATH}; the schema's shape changed "
            "and this reader needs updating rather than silently falling back"
        )
    return tuple(rules)


def schema_paradigm_for(type_name: str) -> str | None:
    """The paradigm the *schema* requires for `type_name`, or None if it says nothing."""
    for pattern, paradigm in _schema_paradigm_rules():
        if pattern.match(type_name):
            return paradigm
    return None


@functools.lru_cache(maxsize=1)
def catalog() -> dict[str, dict[str, Any]]:
    """The engine's component catalogue, keyed by canonical id."""
    raw = json.loads(gsim_py.catalog())
    return {entry["id"]: entry for entry in raw["components"]}


def defaults_for(type_name: str) -> dict[str, Any]:
    """Every parameter the engine declares for a type, at its default value.

    The emitter requires all of them, not just the interesting ones: omitting
    one fails with `missing-param: block 'sw' is missing required parameter
    'body_g_breakdown'`, which is a true complaint about a document that an
    example has no business making the reader solve.
    """
    entry = catalog().get(type_name)
    if entry is None:
        raise KeyError(
            f"{type_name!r} is not in the engine catalogue. "
            "Example schematics use canonical names only, never aliases."
        )
    fidelities = entry.get("fidelities") or []
    params: dict[str, Any] = {}
    for fidelity in fidelities[:1]:
        for param in fidelity.get("params") or []:
            if "default" in param:
                params[param["id"]] = param["default"]
    return params


def placement_for(type_name: str) -> dict[str, str]:
    r"""The paradigm the schema requires and the domain the engine declares.

    The paradigm comes from the schema, not the catalogue, where the two disagree --
    and for `routing.*` they do. `gsim_py.catalog()` reports `routing.ground` as
    `paradigm: physical-network`, which is defensible electrically: a ground node is
    part of the physical network. The schema keys paradigm off the type prefix and
    requires `^routing\.` to say `routing`, which is defensible structurally.

    The document has to satisfy the schema, so the schema wins here. Copying the
    catalogue instead is why every committed example carried
    `paradigm: physical-network` on its ground block and failed the editor's
    validator with `/model/blocks/8/paradigm: must be equal to constant` before the
    canvas ever appeared (#146).

    Whether the *catalogue* should also change is a separate question for gsim-core;
    until it is settled this is the one place the two have to be reconciled, and it
    is better that it be explicit here than silently right in only one of them.
    """
    entry = catalog().get(type_name)
    if entry is None:
        raise KeyError(f"{type_name!r} is not in the engine catalogue")
    placement = {key: entry[key] for key in _PLACEMENT_KEYS if entry.get(key)}
    required = schema_paradigm_for(type_name)
    if required is not None:
        placement["paradigm"] = required
    return placement


#: Horizontal and vertical pitch of the layout grid these examples place on.
#:
#: Chosen so that two blocks in different cells *cannot* overlap, rather than
#: happening not to. The largest symbol in the catalogue these sheets draw from is
#: 60x60 symbol units (`ideal.switch`), and `SYMBOL_SCALE` is 2, so no block
#: occupies more than 120x120 document units. A pitch of 160x140 leaves 40 units
#: of horizontal gutter for a refdes and 20 vertical, and makes the no-overlap
#: property a consequence of the grid instead of something to re-check by eye.
#:
#: `auto_arrange()` used a 40-unit grid, a third of a symbol's width, which is the
#: whole of #145's first fault.
CELL = (160, 140)


def cell(col: int, row: int) -> tuple[int, int]:
    """The document coordinate of layout cell `(col, row)`.

    Coordinates are the symbol's top-left corner, which is what `Block.position`
    means to the renderer -- see `getBlockBoundingBox`.
    """
    return (col * CELL[0], row * CELL[1])


def add(
    sheet,
    type_name: str,
    block_id: str,
    *,
    at: tuple[int, int] | None = None,
    rotation: int = 0,
    **overrides: Any,
):
    """Add a block with the engine's declared defaults, overridden as given.

    Unknown parameter names are rejected here rather than silently ignored: a
    typo in an example's value would otherwise produce a circuit that compiles
    and simulates the wrong thing, which is worse than one that does not build.

    `at` and `rotation` are keyword-only and separate from the parameters, so a
    coordinate can never be mistaken for a component value by either side. They
    exist because `auto_arrange()` is the wrong tool for these sheets: it lays
    out on a 40-unit grid while a symbol is 60x40 symbol units and `SYMBOL_SCALE`
    is 2, so every block occupied 120x80 and sat on top of its neighbours. The
    committed buck had 18 overlapping pairs, the PSFB 87 (#145). An example is
    the one artefact whose job is to be legible the first time it is opened, so
    its layout belongs in its generator where a person chose it.
    """
    params = defaults_for(type_name)
    unknown = set(overrides) - set(params)
    if unknown and params:
        raise KeyError(
            f"{type_name} has no parameter(s) {sorted(unknown)}; it declares {sorted(params)}"
        )
    params.update(overrides)
    placement = placement_for(type_name)
    if at is not None:
        placement["at"] = at  # type: ignore[assignment]
    if rotation:
        placement["rotation"] = rotation  # type: ignore[assignment]
    return sheet.add(type_name, id=block_id, params=params, **placement)


def write_document(
    sheet,
    path: Any,
    *,
    t_end: float,
    t_step: float,
    t_start: float = 0.0,
    analysis_id: str = "tran",
) -> str:
    """Save `sheet` to `path` with a TRAN analysis written into the document.

    The analysis has to be injected into the saved JSON because `gsim_tools` has
    no way to express a simulation directive -- `Schematic` models blocks, wires
    and params, and the `simulation` object is not among them. Worth an upstream
    issue; until then this is the one place that knows how to add it, rather than
    five copies of the same dictionary.

    Why it matters that it is there at all: with `"simulation": {}` the editor's
    `buildAnalysisPayload` finds no analyses, falls back to the v1 sim-settings
    store and runs *its* default of `t_end = 10 s`. On a converter switching at
    100 kHz that is a million switching periods sampled a few thousand times. The
    run completes and the waveform contains nothing a person can read (#145).

    `t_end` and `t_step` are per-example on purpose. Every one of these sheets
    switches at 100 kHz, but their settling times differ by more than an order of
    magnitude -- an output RC of 1.1 ms on the buck against 40 ms on the PFC
    stage -- so one window copied across all five would be wrong for four of them.
    """
    document = json.loads(sheet.save())
    model = document.get("model", document)
    model["simulation"] = {
        "default_analysis": analysis_id,
        "analyses": [
            {
                "id": analysis_id,
                "type": "TRAN",
                "t_start": t_start,
                "t_end": t_end,
                "t_step": t_step,
            }
        ],
    }
    text = json.dumps(document, indent=2) + "\n"
    pathlib.Path(path).write_text(text)
    return text
